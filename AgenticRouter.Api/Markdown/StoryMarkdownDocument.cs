using System.Globalization;
using System.Net;
using System.Text.RegularExpressions;
using Markdig;
using Markdig.Renderers;
using Markdig.Renderers.Html;
using Markdig.Renderers.Html.Inlines;
using Markdig.Syntax;
using Markdig.Syntax.Inlines;
using Markdown.ColorCode;

namespace AgenticRouter.Api.Markdown;

// Render-only source coordinates. The source Markdown is never rewritten.
internal static class StoryMarkdownDocument
{
  private static readonly MarkdownPipeline Pipeline = new MarkdownPipelineBuilder()
    .UseAdvancedExtensions().UsePreciseSourceLocation().UseColorCode(HtmlFormatterType.Css).Build();
  private static readonly Regex Anchor = new("""\A<a\s+(?:id|name)\s*=\s*(?:"(?<id>[^"<>\s]+)"|'(?<id>[^'<>\s]+)'|(?<id>[^\s'"<>]+))\s*>\s*</a>\z""",
    RegexOptions.IgnoreCase | RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));

  public static string Render(string markdown)
  {
    var document = Markdig.Markdown.Parse(markdown, Pipeline);
    var anchors = new Dictionary<MarkdownObject, string>();
    foreach (var item in document.Descendants())
    {
      var attributes = item.GetAttributes();
      // Source coordinates are generated by the Host, never accepted from Markdown attributes.
      attributes.Properties?.RemoveAll(pair => pair.Key.StartsWith("data-story-", StringComparison.OrdinalIgnoreCase));
      if (item.Span.Start >= 0 && item.Span.End >= item.Span.Start)
      {
        attributes.AddProperty("data-story-start", item.Span.Start.ToString(CultureInfo.InvariantCulture));
        attributes.AddProperty("data-story-end", (item.Span.End + 1).ToString(CultureInfo.InvariantCulture));
      }
      if (item is HtmlBlock block)
      {
        var match = Anchor.Match(block.Lines.ToString().Trim());
        if (match.Success) anchors[item] = WebUtility.HtmlDecode(match.Groups["id"].Value);
      }
      else if (item is HtmlInline inline && inline.NextSibling is HtmlInline closing)
      {
        var match = Anchor.Match(inline.Tag + closing.Tag);
        if (match.Success)
        {
          anchors[item] = WebUtility.HtmlDecode(match.Groups["id"].Value);
          anchors[closing] = "";
        }
      }
    }
    using var writer = new StringWriter(CultureInfo.InvariantCulture);
    var renderer = new HtmlRenderer(writer);
    Pipeline.Setup(renderer);
    renderer.ObjectRenderers.Insert(0, new AnchorBlockRenderer(anchors));
    renderer.ObjectRenderers.Insert(0, new AnchorInlineRenderer(anchors));
    renderer.ObjectWriteBefore += (_, item) =>
    {
      if (IsMappedText(item)) renderer.Write($"<span data-story-start=\"{item.Span.Start}\" data-story-end=\"{item.Span.End + 1}\">");
    };
    renderer.ObjectWriteAfter += (_, item) =>
    {
      if (IsMappedText(item)) renderer.Write("</span>");
    };
    renderer.Render(document);
    return writer.ToString();
  }

  private static bool IsMappedText(MarkdownObject item) => item is LiteralInline or CodeInline or HtmlEntityInline or AutolinkInline;

  private static void WriteAnchor(HtmlRenderer renderer, string id, MarkdownObject source)
  {
    if (id.Length > 0) renderer.Write($"<span id=\"{WebUtility.HtmlEncode(id)}\" data-story-start=\"{source.Span.Start}\" data-story-end=\"{source.Span.End + 1}\"></span>");
  }

  private sealed class AnchorBlockRenderer(Dictionary<MarkdownObject, string> anchors) : HtmlBlockRenderer
  {
    protected override void Write(HtmlRenderer renderer, HtmlBlock obj)
    {
      if (anchors.TryGetValue(obj, out var id)) WriteAnchor(renderer, id, obj);
      else renderer.WriteEscape(obj.Lines.ToString());
    }
  }

  private sealed class AnchorInlineRenderer(Dictionary<MarkdownObject, string> anchors) : HtmlInlineRenderer
  {
    protected override void Write(HtmlRenderer renderer, HtmlInline obj)
    {
      if (anchors.TryGetValue(obj, out var id)) WriteAnchor(renderer, id, obj);
      else renderer.WriteEscape(obj.Tag);
    }
  }
}
